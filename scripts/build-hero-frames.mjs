// BUILD THE HERO IMAGE SEQUENCE
// =============================
// Turns the raw 546-frame render dump in public/Images/ (2725×1536 PNG, ~3 MB
// each, ~1.2 GB total — unshippable) into a web-ready scroll sequence.
//
//   · SUBSAMPLE every Nth source frame (STEP) → ~137 frames. A scrubbed scroll
//     sequence is smooth at ~120-150 frames; 546 is video-grade overkill and
//     would be ~26 MB even optimised.
//   · RESIZE to WIDTH and encode WebP at QUALITY → ~47 KB/frame, ~6.5 MB total.
//   · Only frame 0 must paint for LCP; the rest stream in behind it.
//
// The raw public/Images/ folder is PRESERVED on disk and gitignored — it is
// never referenced by the app and never shipped.
//
// Output: public/hero/frame-000.webp … + poster.webp + src/data/heroSequence.ts
// Run:    node scripts/build-hero-frames.mjs
import sharp from 'sharp'
import fs from 'node:fs'
import path from 'node:path'

const SRC = 'public/Images'
const OUT = 'public/hero'
const STEP = 4 // keep every 4th source frame
const WIDTH = 1440 // desktop sequence width
const QUALITY = 64
const POSTER_WIDTH = 1600 // the still used as the LCP poster + mobile hero
const CONCURRENCY = 8

const files = fs
  .readdirSync(SRC)
  .filter((f) => /^frame-\d+\.png$/i.test(f))
  .sort()
if (!files.length) {
  console.error(`No frames found in ${SRC}`)
  process.exit(1)
}

const picked = files.filter((_, i) => i % STEP === 0)
fs.rmSync(OUT, { recursive: true, force: true })
fs.mkdirSync(OUT, { recursive: true })

console.log(`${files.length} source frames → keeping every ${STEP}th = ${picked.length} frames`)

let dims = null
let totalBytes = 0
let done = 0

async function encodeOne(srcName, i) {
  const buf = await sharp(path.join(SRC, srcName))
    .resize(WIDTH)
    .webp({ quality: QUALITY, effort: 4 })
    .toBuffer({ resolveWithObject: true })
  const name = `frame-${String(i).padStart(3, '0')}.webp`
  fs.writeFileSync(path.join(OUT, name), buf.data)
  totalBytes += buf.data.length
  if (!dims) dims = { width: buf.info.width, height: buf.info.height }
  done++
  if (done % 20 === 0 || done === picked.length) {
    process.stdout.write(`\r  encoded ${done}/${picked.length}`)
  }
}

// Simple concurrency pool.
const queue = picked.map((name, i) => ({ name, i }))
async function worker() {
  while (queue.length) {
    const { name, i } = queue.shift()
    await encodeOne(name, i)
  }
}
await Promise.all(Array.from({ length: CONCURRENCY }, worker))
process.stdout.write('\n')

// Poster (frame 0) at a higher resolution — the LCP element + the mobile still.
const poster = await sharp(path.join(SRC, picked[0]))
  .resize(POSTER_WIDTH)
  .webp({ quality: 70, effort: 4 })
  .toBuffer()
fs.writeFileSync(path.join(OUT, 'poster.webp'), poster)

const manifest = {
  count: picked.length,
  width: dims.width,
  height: dims.height,
  aspect: +(dims.width / dims.height).toFixed(4),
}
fs.writeFileSync(path.join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 2))

// A typed constant the component imports — no runtime manifest fetch.
fs.writeFileSync(
  'src/data/heroSequence.ts',
  `// GENERATED by scripts/build-hero-frames.mjs — do not edit by hand.
// The homepage scroll-cinematography sequence, built from the client's rendered
// walkthrough frames. Re-run the script to regenerate.
export const HERO_SEQUENCE = ${JSON.stringify(
    { ...manifest, dir: '/hero', frame: 'frame-', ext: '.webp', pad: 3 },
    null,
    2,
  )} as const
`,
)

console.log(
  `\nDONE · ${picked.length} frames · ${(totalBytes / 1024 / 1024).toFixed(1)} MB total · ` +
    `${(totalBytes / picked.length / 1024).toFixed(0)} KB/frame · ${dims.width}×${dims.height}`,
)
console.log(`poster.webp ${(poster.length / 1024).toFixed(0)} KB · manifest + src/data/heroSequence.ts written`)
